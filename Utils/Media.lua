-- Font / texture registry.  Every asset ships inside the addon (Assets/).
-- NOTE: the paths are built from ADDON_NAME so the addon folder must stay named "MonetUI".

local ADDON_NAME, ns = ...

local Media = {}
ns.Media = Media

local ASSET = "Interface\\AddOns\\" .. ADDON_NAME .. "\\Assets\\"

Media.asset        = ASSET
Media.fontsDir     = ASSET .. "Fonts\\"
Media.texturesDir  = ASSET .. "Textures\\"

-- Every font we set is a pixel (bitmap-grid) face, always rendered with MONOCHROME (see Media.fontFlags) so edges stay hard -- no OUTLINE ever, a 1px outline smears the grid blocks of a pixel font.
--   pixel    Fusion Pixel 12px (SIL OFL, license: Assets/Fonts/OFL-FusionPixel.txt).
--            True rectangle outlines on a grid of em/12, so one design pixel equals one screen pixel at the multiples of 12 (12, 24) our call sites use; off-grid text is hardened by MONOCHROME.
--   cooldown Super Effective, a tiny ASCII-only pixel face for countdown digits -- digits only, never pass Chinese to it.
-- Unknown keys fall back to `pixel`, so legacy saved settings that still say "roadway", "number", "combat" or "default" resolve to the pixel font.
Media.font = {
    pixel    = ASSET .. "Fonts\\fusion-pixel-12.ttf",
    cooldown = ASSET .. "Fonts\\super-effective.ttf",
}

-- Default render flags for every FontString we set: MONOCHROME switches antialiasing off -- on the grid it changes nothing, off the grid it turns the grey fringe into hard stair-steps instead of blur.
Media.fontFlags = "MONOCHROME"

--- Snap a font size onto the pixel grid (multiples of 12) and to a sane floor.
function Media:SnapSize(size)
    size = tonumber(size) or 12
    return math.max(12, math.floor((size + 6) / 12) * 12)
end

--- The size of ONE physical screen pixel expressed in UI units ("mult").
-- Borders, hairlines and insets sized N * Media:Mult() stay exactly N physical pixels at any resolution and UI scale.  Measured rather than derived (UIParent spans the screen by contract, so GetHeight()/physicalHeight is units-per-pixel by definition) -- it stays correct whatever way this client reports its logical resolution.
--   mult ~= 1 on a scaled UI (e.g. ~0.99 at 1080p scale 0.72); the fractional value is the point: frame units are not px.
function Media:Mult()
    local physH = select(2, GetPhysicalScreenSize and GetPhysicalScreenSize())
    local h = UIParent and UIParent.GetHeight and UIParent:GetHeight()
    if not physH or physH <= 0 or not h or h ~= h or h <= 0 then return 1 end
    local m = h / physH
    -- Sanity band: a screen reported in logical units would collapse this to 1 (harmless), a broken ratio outside any real UI scale falls back to 1.
    if m ~= m or m < 0.2 or m > 6 then return 1 end
    return m
end

