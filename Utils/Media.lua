-- Utils/Media.lua
-- Font / texture registry.  Every asset ships inside the addon (Assets/).
--
-- NOTE: the paths are built from ADDON_NAME so the addon folder must stay named
--       "MonetUI".

local ADDON_NAME, ns = ...

local Media = {}
ns.Media = Media

local ASSET = "Interface\\AddOns\\" .. ADDON_NAME .. "\\Assets\\"

Media.asset        = ASSET
Media.fontsDir     = ASSET .. "Fonts\\"
Media.texturesDir  = ASSET .. "Textures\\"

-- Fonts -----------------------------------------------------------------------
Media.font = {
    pixel    = ASSET .. "Fonts\\Pingfangpixel.ttf",    -- body text (Chinese-friendly pixel font)
    combat   = ASSET .. "Fonts\\combat.ttf",           -- large combat numbers
    cooldown = ASSET .. "Fonts\\super-effective.ttf",  -- cooldown countdown
    roadway  = ASSET .. "Fonts\\roadway.ttf",          -- headings / decorative
    default  = "Fonts\\FRIZQT__.TTF",
    number   = "Fonts\\ARIALN.TTF",
}

-- Textures --------------------------------------------------------------------
Media.texture = {
    blank     = "Interface\\Buttons\\WHITE8X8",
    statusbar = "Interface\\TargetingFrame\\UI-StatusBar",
    mask      = "Interface\\CharacterFrame\\TempPortraitAlphaMask",
    ring      = "Interface\\Minimap\\MiniMap-TrackingBorder",
    glow      = "Interface\\SpellActivationOverlay\\IconAlertAnts",
    -- 256x256 alpha mask that keeps only the middle 190px band, turning the
    -- circular minimap into a 256x190 rectangle.  Generated by
    -- tools/make-minimap-mask.ps1 (transparent black top and bottom 33px,
    -- opaque white in between), so no third-party art is shipped for it.
    minimapRect = ASSET .. "Textures\\minimap-rect-mask",

    -- Self-drawn UI textures, generated by tools/make-ui-textures.ps1
    -- (same pixel data ships as .tga for the game and .png for the preview page:
    --  docs/texture-preview.html).  Everything with a "monet-" key except the
    --  role icons is painted near-white on purpose -- tint it with SetVertexColor;
    --  the three role icons carry their semantic colours, never tint those.

    -- status bar fill: full-bleed white vertical gradient (bright top, shaded
    -- bottom), stretched to the bar -- keeps volume at any height once tinted
    ["monet-barfill"]      = ASSET .. "Textures\\monet-barfill",

    -- window chrome
    ["monet-close-normal"]  = ASSET .. "Textures\\monet-close-normal",
    ["monet-close-hover"]   = ASSET .. "Textures\\monet-close-hover",
    ["monet-close-push"]    = ASSET .. "Textures\\monet-close-push",
    ["monet-win-minimize"]  = ASSET .. "Textures\\monet-win-minimize",
    ["monet-win-maximize"]  = ASSET .. "Textures\\monet-win-maximize",
    ["monet-win-restore"]   = ASSET .. "Textures\\monet-win-restore",

    -- generic glyphs
    ["monet-check"]         = ASSET .. "Textures\\monet-check",
    ["monet-radio"]         = ASSET .. "Textures\\monet-radio",
    ["monet-plus"]          = ASSET .. "Textures\\monet-plus",
    ["monet-minus"]         = ASSET .. "Textures\\monet-minus",
    ["monet-chevron-down"]  = ASSET .. "Textures\\monet-chevron-down",
    ["monet-chevron-up"]    = ASSET .. "Textures\\monet-chevron-up",
    ["monet-arrow-left"]    = ASSET .. "Textures\\monet-arrow-left",
    ["monet-arrow-right"]   = ASSET .. "Textures\\monet-arrow-right",
    ["monet-search"]        = ASSET .. "Textures\\monet-search",

    -- role icons (fixed colours -- do NOT SetVertexColor)
    ["monet-role-tank"]     = ASSET .. "Textures\\monet-role-tank",
    ["monet-role-heal"]     = ASSET .. "Textures\\monet-role-heal",
    ["monet-role-dps"]      = ASSET .. "Textures\\monet-role-dps",

    -- decoration
    ["monet-brush-stroke"]  = ASSET .. "Textures\\monet-brush-stroke",
    ["monet-corner"]        = ASSET .. "Textures\\monet-corner",
}

--- Resolve a font key to a path (unknown keys fall back to the pixel font).
function Media:Font(key)
    return self.font[key] or self.font.pixel
end

--- Resolve a texture key to a path (unknown keys fall back to the blank texture).
function Media:Texture(key)
    return self.texture[key] or self.texture.blank
end
